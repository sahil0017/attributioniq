-- 4.1 Outcome breakdown per model: link method, reason, counted
SELECT model, link_method, reason, counted, count(*) AS orders, sum(revenue_inr) AS revenue_inr
FROM order_attribution
GROUP BY model, link_method, reason, counted
ORDER BY model, orders DESC;

-- 4.2 Revenue only counts paid, non-test orders (expect 0 rows)
SELECT a.order_id, a.model, o.financial_status, o.is_test, a.revenue_inr
FROM order_attribution a
JOIN orders o USING (order_id)
WHERE a.counted
  AND (o.is_test OR o.financial_status <> 'paid');

-- 4.3 Touch must be inside the attribution window and before the order (expect 0 rows)
SELECT order_id, model, touch_at, order_at, window_days
FROM order_attribution
WHERE touch_at IS NOT NULL
  AND (touch_at > order_at OR touch_at < order_at - make_interval(days => window_days));

-- 4.4 Last-click vs first-click channel comparison
SELECT model, channel, count(*) FILTER (WHERE counted) AS orders,
       sum(revenue_inr) FILTER (WHERE counted) AS revenue_inr
FROM order_attribution
GROUP BY model, channel
ORDER BY channel, model;

-- 4.5 Orders where the two models disagree on channel
SELECT l.order_id, l.channel AS last_click_channel, f.channel AS first_click_channel,
       l.touch_at AS last_touch, f.touch_at AS first_touch
FROM order_attribution l
JOIN order_attribution f ON f.order_id = l.order_id AND f.model = 'first_click'
WHERE l.model = 'last_click' AND l.channel <> f.channel
ORDER BY l.order_at DESC
LIMIT 50;

-- 4.6 Unattributed paid revenue by reason (what we could not link)
SELECT reason, link_method, count(*) AS orders, sum(revenue_inr) AS revenue_inr
FROM order_attribution
WHERE model = 'last_click' AND NOT counted
GROUP BY reason, link_method;

