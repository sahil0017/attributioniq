-- 5.2 Current (latest-snapshot) spend by platform in INR
SELECT platform, sum(spend_inr) AS spend_inr
FROM ad_spend_current
GROUP BY platform
ORDER BY platform;

-- 5.3 Daily channel report (revenue, orders, spend, ROAS) — last click
SELECT * FROM channel_daily(
    (SELECT min(order_at AT TIME ZONE 'UTC')::date FROM order_attribution),
    (SELECT max(order_at AT TIME ZONE 'UTC')::date FROM order_attribution),
    'last_click');

-- 5.4 Channel totals over the full data range, both models side by side
SELECT m.model, d.channel,
       sum(d.orders)      AS orders,
       sum(d.revenue_inr) AS revenue_inr,
       sum(d.spend_inr)   AS spend_inr,
       round(sum(d.revenue_inr) / nullif(sum(d.spend_inr), 0), 2) AS roas
FROM (VALUES ('last_click'), ('first_click')) AS m(model)
CROSS JOIN LATERAL channel_daily(
    (SELECT min(order_at AT TIME ZONE 'UTC')::date FROM order_attribution),
    (SELECT max(order_at AT TIME ZONE 'UTC')::date FROM order_attribution),
    m.model) d
GROUP BY m.model, d.channel
ORDER BY m.model, revenue_inr DESC;

-- 5.5 Monthly channel report (last click)
SELECT date_trunc('month', day)::date AS month, channel,
       sum(orders) AS orders, sum(revenue_inr) AS revenue_inr, sum(spend_inr) AS spend_inr,
       round(sum(revenue_inr) / nullif(sum(spend_inr), 0), 2) AS roas
FROM channel_daily(
    (SELECT min(order_at AT TIME ZONE 'UTC')::date FROM order_attribution),
    (SELECT max(order_at AT TIME ZONE 'UTC')::date FROM order_attribution),
    'last_click')
GROUP BY 1, 2
ORDER BY 1, 2;

-- 5.6 Report reconciliation: counted revenue equals sum of channel_daily (expect diff = 0)
SELECT (SELECT coalesce(sum(revenue_inr), 0) FROM order_attribution
         WHERE model = 'last_click' AND counted)
     - (SELECT coalesce(sum(revenue_inr), 0) FROM channel_daily(
            (SELECT min(order_at AT TIME ZONE 'UTC')::date FROM order_attribution),
            (SELECT max(order_at AT TIME ZONE 'UTC')::date FROM order_attribution),
            'last_click')) AS diff;
