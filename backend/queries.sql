-- 3.1 Merged persons and canonical-person check (merged chains should resolve)
SELECT count(*) FILTER (WHERE merged_into IS NULL)     AS canonical_persons,
       count(*) FILTER (WHERE merged_into IS NOT NULL) AS merged_persons
FROM persons;

-- 3.2 Identifiers pointing at a non-canonical (merged) person (expect 0 rows)
SELECT pi.id_type, pi.id_value, pi.person_id
FROM person_identifiers pi
JOIN persons p ON p.person_id = pi.person_id
WHERE p.merged_into IS NOT NULL;

-- 3.3 People with several anonymous IDs (cross-device / merged journeys)
SELECT person_id, count(*) FILTER (WHERE id_type = 'anon')  AS anon_ids,
       count(*) FILTER (WHERE id_type = 'email') AS emails
FROM person_identifiers
GROUP BY person_id
HAVING count(*) FILTER (WHERE id_type = 'anon') > 1
ORDER BY anon_ids DESC
LIMIT 20;

-- 3.4 Sessions per channel with average duration and size
SELECT channel, count(*) AS sessions,
       round(avg(duration_s)) AS avg_duration_s,
       round(avg(event_count), 2) AS avg_events
FROM sessions
GROUP BY channel
ORDER BY sessions DESC;

-- 3.5 Session gap rule: consecutive sessions of one anonymous_id must be more than the
--     gap apart (expect 0 rows)
SELECT *
FROM (
    SELECT s.anonymous_id, s.session_id, s.started_at,
           lag(s.ended_at) OVER (PARTITION BY s.anonymous_id ORDER BY s.started_at) AS prev_ended_at
    FROM sessions s
) x, (SELECT value::int AS minutes FROM settings WHERE key = 'session_gap_minutes') g
WHERE x.prev_ended_at IS NOT NULL
  AND x.started_at - x.prev_ended_at <= make_interval(mins => g.minutes);

-- 3.6 Event counts reconcile with sessions (expect 0 rows)
SELECT s.session_id, s.event_count, count(e.event_id) AS linked_events
FROM sessions s
LEFT JOIN events e ON e.session_id = s.session_id
GROUP BY s.session_id, s.event_count
HAVING s.event_count <> count(e.event_id)
LIMIT 20;

